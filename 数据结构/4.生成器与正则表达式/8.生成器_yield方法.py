"""
数据结构.4.生成器与正则表达式.7.生成器_推导式写法 的 Docstring

生成器(Generator)核心概念
    生成器是一种特殊的迭代器，它基于数据规则，在迭代过程中按需生成元素，
    而不是一次性将所有元素加载到内存中，从而实现高效的内存使用。
核心目的
    节省内存：
        特别适合处理大数据集或无限序列，避免一次性占用大量内存。
    惰性计算：
        只有在迭代时才计算并返回下一个值，计算是 “懒加载” 的。
主要实现方式
    1. 生成器表达式（推导式写法）
        语法与列表推导式类似，只是将方括号 [] 换成圆括号 ()。

2. yield 关键字
    在函数中使用 yield 替代 return,函数就变成了生成器函数。每次调用 next() 或迭代时，
    函数执行到 yield 处暂停，并返回当前值；下次迭代时从暂停处继续执行。

生成器与迭代器的关系
    生成器是迭代器的子类，它自动实现了 __iter__() 和 __next__() 方法，
    因此可以直接用 for 循环或 next() 函数遍历。
    与手动实现的迭代器相比，生成器的代码更简洁，且自动管理了迭代状态。

"""
#推导式写法
my_gt = (i for i in range(1,11))

#yield方法
#定义函数,储存到生成器中,并返回
def my_fun():
    # my_list = []              #创建
    # for i in range(1,11):
    #     my_list.append(i)     #添加
    # return my_list            #返回

    #效果类似上述代码
    #yield在这里:   1.创建生成器对象,2.把值储存到生成器中,3.返回
    for i in range(1,11):
        yield i

my_gt2= my_fun()

print(type(my_gt2))

print(next(my_gt2))
print(next(my_gt2))
print('-'*20)
for i in my_gt2:
    print(i)